#!/usr/bin/env bash
#
# Generate .env.bak, RS256 JWT keys, and random secrets for auth-service.
#
# Reads the env vars the service actually consumes (see src/main.rs):
#   required: DATABASE_PATH, JWT_PRIVATE_KEY_PATH, JWT_PUBLIC_KEYS_DIR,
#             JWT_SIGNING_KEY_ID, JWT_ISSUER, JWT_AUDIENCE,
#             AUTH_ADMIN_API_KEY (>=32 bytes), AUTH_PASSWORD_PEPPER (>=32 bytes)
#   optional: JWT_LEGACY_KEY_ID, ACCESS_TOKEN_TTL_SECONDS,
#             JWT_VERIFY_CACHE_CAPACITY, AUTH_ADDR, AUTH_COOKIE_SECURE
#
# Storage is SQLite (tokio-rusqlite): DATABASE_PATH is a file path, not a URL.
# The public key file is named "<JWT_SIGNING_KEY_ID>.pem".
#
# Usage:
#   scripts/gen-env.sh            # generate .env.bak + keys if missing
#   scripts/gen-env.sh --force    # overwrite existing .env.bak and keys
#
# Overridable via environment, e.g.:
#   JWT_ISSUER=https://id.example.com/ JWT_AUDIENCE=my-api scripts/gen-env.sh

set -euo pipefail

# Resolve the auth-service root (parent of this script's dir) regardless of CWD.
SCRIPT_DIR="$(cd -- "$(dirname -- "${BASH_SOURCE[0]}")" && pwd)"
ROOT_DIR="$(cd -- "${SCRIPT_DIR}/.." && pwd)"
cd "${ROOT_DIR}"

FORCE=0
for arg in "$@"; do
  case "${arg}" in
    --force|-f) FORCE=1 ;;
    -h|--help) grep '^#' "$0" | sed 's/^# \{0,1\}//'; exit 0 ;;
    *) echo "unknown argument: ${arg}" >&2; exit 2 ;;
  esac
done

command -v openssl >/dev/null 2>&1 || { echo "error: openssl is required" >&2; exit 1; }

# ---- Configuration (override by exporting before running) -------------------
DATABASE_PATH="${DATABASE_PATH:-./data/auth.db}"
JWT_PRIVATE_KEY_PATH="${JWT_PRIVATE_KEY_PATH:-./resources/private/private-key.pem}"
JWT_PUBLIC_KEYS_DIR="${JWT_PUBLIC_KEYS_DIR:-./resources}"
JWT_SIGNING_KEY_ID="${JWT_SIGNING_KEY_ID:-current}"
JWT_LEGACY_KEY_ID="${JWT_LEGACY_KEY_ID:-${JWT_SIGNING_KEY_ID}}"
JWT_ISSUER="${JWT_ISSUER:-https://proselin.id.vn/}"
JWT_AUDIENCE="${JWT_AUDIENCE:-your-api}"
ACCESS_TOKEN_TTL_SECONDS="${ACCESS_TOKEN_TTL_SECONDS:-900}"
JWT_VERIFY_CACHE_CAPACITY="${JWT_VERIFY_CACHE_CAPACITY:-10000}"
AUTH_ADDR="${AUTH_ADDR:-127.0.0.1:8081}"
AUTH_COOKIE_SECURE="${AUTH_COOKIE_SECURE:-false}"

ENV_FILE="${ROOT_DIR}/.env"
PUB_KEY_FILE="${JWT_PUBLIC_KEYS_DIR}/${JWT_SIGNING_KEY_ID}.pem"

# ---- RS256 keypair ----------------------------------------------------------
gen_keys() {
  mkdir -p "$(dirname -- "${JWT_PRIVATE_KEY_PATH}")" "${JWT_PUBLIC_KEYS_DIR}"
  if [[ -f "${JWT_PRIVATE_KEY_PATH}" && -f "${PUB_KEY_FILE}" && "${FORCE}" -eq 0 ]]; then
    echo "keys exist, keeping: ${JWT_PRIVATE_KEY_PATH}, ${PUB_KEY_FILE}"
    return
  fi
  echo "generating RS256 keypair -> ${JWT_PRIVATE_KEY_PATH}, ${PUB_KEY_FILE}"
  openssl genpkey -algorithm RSA -pkeyopt rsa_keygen_bits:2048 \
    -out "${JWT_PRIVATE_KEY_PATH}" 2>/dev/null
  openssl rsa -in "${JWT_PRIVATE_KEY_PATH}" -pubout -out "${PUB_KEY_FILE}" 2>/dev/null
  chmod 600 "${JWT_PRIVATE_KEY_PATH}"
}

# 48 random bytes -> base64 (64 chars, comfortably over the 32-byte minimum).
rand_secret() { openssl rand -base64 48 | tr -d '\n'; }

# ---- .env.bak -------------------------------------------------------------------
gen_env() {
  if [[ -f "${ENV_FILE}" && "${FORCE}" -eq 0 ]]; then
    echo "error: ${ENV_FILE} already exists. Re-run with --force to overwrite." >&2
    exit 1
  fi

  local admin_key pepper
  admin_key="$(rand_secret)"
  pepper="$(rand_secret)"

  cat >"${ENV_FILE}" <<EOF
# Auth service environment. Generated by scripts/gen-env.sh on $(date -u +%Y-%m-%dT%H:%M:%SZ).
# Storage is SQLite via tokio-rusqlite: DATABASE_PATH is a FILE PATH, not a URL.
DATABASE_PATH=${DATABASE_PATH}

# RS256 keys. The public key file name must equal JWT_SIGNING_KEY_ID: ${JWT_SIGNING_KEY_ID}.pem
JWT_PRIVATE_KEY_PATH=${JWT_PRIVATE_KEY_PATH}
JWT_PUBLIC_KEYS_DIR=${JWT_PUBLIC_KEYS_DIR}
JWT_SIGNING_KEY_ID=${JWT_SIGNING_KEY_ID}
JWT_LEGACY_KEY_ID=${JWT_LEGACY_KEY_ID}

JWT_ISSUER=${JWT_ISSUER}
JWT_AUDIENCE=${JWT_AUDIENCE}

# Secrets (>= 32 bytes), generated with: openssl rand -base64 48
AUTH_ADMIN_API_KEY="${admin_key}"
AUTH_PASSWORD_PEPPER="${pepper}"

# Optional (shown with defaults).
ACCESS_TOKEN_TTL_SECONDS=${ACCESS_TOKEN_TTL_SECONDS}
JWT_VERIFY_CACHE_CAPACITY=${JWT_VERIFY_CACHE_CAPACITY}
AUTH_ADDR=${AUTH_ADDR}
# Set false only for local HTTP development.
AUTH_COOKIE_SECURE=${AUTH_COOKIE_SECURE}
# ENABLE_IMPLICIT_FLOW=true
EOF
  chmod 600 "${ENV_FILE}"
  echo "wrote ${ENV_FILE}"
}

gen_keys
gen_env

cat <<EOF

Done. The binary does not auto-load .env, so run with:
  cd ${ROOT_DIR}
  set -a; . ./.env; set +a
  cargo run -p auth_service
EOF
